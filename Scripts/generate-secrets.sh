#!/bin/sh
# Generates AppBox/Generated/AppBoxSecrets.swift (gitignored) from the repo-root .env file
# (gitignored; see .env.example) or, failing that, the process environment. Values default to
# empty strings so secret-less builds (fresh clones, CI) still compile — the backend client and
# Dropbox login just won't be functional until a .env is provided.
#
# Runs as a pre-compile build phase of both the AppBox and AppBoxCLI targets.
set -eu

SRCROOT="${SRCROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
ENV_FILE="$SRCROOT/.env"

if [ -f "$ENV_FILE" ]; then
	# shellcheck disable=SC1090
	set -a; . "$ENV_FILE"; set +a
fi

APPBOX_CLIENT_TOKEN="${APPBOX_CLIENT_TOKEN:-}"
DROPBOX_APP_KEY="${DROPBOX_APP_KEY:-}"

CONTENT="// Generated by Scripts/generate-secrets.sh from .env — DO NOT EDIT, DO NOT COMMIT (gitignored).
enum AppBoxSecrets {
	/// Must match the backend's APPBOX_CLIENT_TOKEN (install-helper).
	static let clientToken = \"$APPBOX_CLIENT_TOKEN\"
	/// The Dropbox OAuth client_id (must match the Info.plist db- URL scheme).
	static let dropboxAppKey = \"$DROPBOX_APP_KEY\"
}"

# One file PER TARGET under a repo-root dir (never inside the CLI's synchronized folder). Each
# target's Generate-Secrets phase declares its own file as an output, so the new build system
# accepts it as a Sources input on a clean build; distinct paths avoid a "multiple commands
# produce" conflict when AppBox builds its AppBoxCLI dependency in the same graph.
for TARGET in AppBox AppBoxCLI; do
	OUT_DIR="$SRCROOT/Generated/$TARGET"
	mkdir -p "$OUT_DIR"
	OUT="$OUT_DIR/AppBoxSecrets.swift"
	# Only rewrite on change so incremental builds stay incremental.
	if [ ! -f "$OUT" ] || [ "$(cat "$OUT")" != "$CONTENT" ]; then
		printf '%s\n' "$CONTENT" > "$OUT"
	fi
done
